/**
 * Generates HTML for a user avatar (ReadyPlayerMe SUPPRIMÉ — plus de conflits réseau / DNS).
 * Chaîne fallback : 1) vignette 3D locale → 2) image 2D explicite → 3) DiceBear → 4) initiales gradient
 * @param {Object} user - User object containing avatarUrl or avatar3DUrl
 * @param {string} size - CSS size string (default: "40px")
 * @returns {string} HTML string for the avatar
 */
const DICEBEAR_CDN = "https://api.dicebear.com/7.x/avataaars/svg";

function safeDiceBearSeed(user) {
    const u = user || {};
    const base = (u.id || u._id || u.fullName || u.username || u.email || u.matricule || "user").toString().trim();
    const safe = base.replace(/[^a-zA-Z0-9_-]/g, "") || "wbcuser";
    return encodeURIComponent(safe);
}

function safeInitial(user) {
    const u = user || {};
    return (u.fullName || u.username || u.email || u.matricule || "?").toString().trim().charAt(0).toUpperCase() || "?";
}

function safeUserId(user) {
    const u = user || {};
    return String(u.id || u._id || u.userId || u.matricule || u.email || "").trim();
}

/** Cache for local thumbnail 3D snapshots (generated by hall-scene.js / class-scene.js after GLB load) */
const WBC_AVATAR_THUMB_PREFIX = "wbc_avatar_thumb:";
function getLocalAvatarThumb(user) {
    try {
        const uid = safeUserId(user);
        if (!uid) return null;
        const key = WBC_AVATAR_THUMB_PREFIX + uid;
        const val = localStorage.getItem(key);
        if (!val) return null;
        if (val.length < 32) return null;
        return val;
    } catch { return null; }
}
function setLocalAvatarThumb(user, dataUrl) {
    try {
        const uid = safeUserId(user);
        if (!uid || !dataUrl) return;
        if (dataUrl.length < 32) return;
        localStorage.setItem(WBC_AVATAR_THUMB_PREFIX + uid, dataUrl.substring(0, 800000));
        try {
            window.dispatchEvent(new CustomEvent("wbc:avatarThumbReady", { detail: { userId: uid, dataUrl } }));
        } catch {}
    } catch {}
}

/**
 * Builds a reliable <img>+fallback avatar HTML chain.
 * ReadyPlayerMe SUPPRIMÉ de tous les fallbacks — 0 conflits réseau.
 */
function createAvatarHtml(user, size = "40px") {
    const safeUser = user || {};
    const url = safeUser.avatar3DUrl || safeUser.avatarUrl || safeUser.avatar_url;

    const commonStyle = `width:${size};height:${size};border-radius:50%;border:1px solid #00ff88;display:inline-block;vertical-align:middle;background-color:#333;`;
    const gradient = "linear-gradient(135deg,#6366f1 0%,#ec4899 100%)";
    const initial = safeInitial(safeUser);
    const uid = safeUserId(safeUser);
    const dataAttr = `data-avatar-for="${uid.replace(/"/g, '')}"`;
    const seed = safeDiceBearSeed(safeUser);
    const diceUrl = `${DICEBEAR_CDN}?seed=${seed}&backgroundType=gradientLinear&backgroundColor=b6e3f4,c0aede,d1d4f9,ffdfbf,ffd5dc,cdf5ff,fdcfcf,ffd6e0`;

    const fallbackStyle = `${commonStyle}display:none;align-items:center;justify-content:center;color:#fff;font-weight:bold;background:${gradient};`;

    // 1) Vignette 3D locale → MEILLEUR (vrai visage avatar GLB)
    const localThumb = getLocalAvatarThumb(safeUser);
    if (localThumb) {
        return `<img ${dataAttr} src="${localThumb}" style="${commonStyle}object-fit:cover;display:inline-block;" alt="Avatar"
                onerror="this.onerror=null;this.style.display='none';const fb=this.nextElementSibling;if(fb){fb.style.display='flex';}">
                <div ${dataAttr} style="${fallbackStyle}">${initial}</div>`;
    }

    const isClean2DImage = (u) => {
        if (!u) return false;
        const s = String(u);
        if (s.includes("readyplayer.me") || s.includes("ready-player-me")) return false;
        if (/\.(glb|gltf|vrm)(\?|#|$)/i.test(s)) return false;
        return true;
    };

    // 2) Image 2D explicite valide → affichage direct
    if (isClean2DImage(url)) {
        const resolved = url.startsWith("/") ? `${API_URL || ""}${url}` : url;
        return `<img ${dataAttr} src="${resolved}" style="${commonStyle}object-fit:cover;display:inline-block;" alt="Avatar"
                onerror="this.onerror=null;this.style.display='none';const dice=this.nextElementSibling;const initialEl=this.nextElementSibling?.nextElementSibling;if(dice){dice.style.display='inline-block';}else if(initialEl){initialEl.style.display='flex';}">
                <img ${dataAttr} src="${diceUrl}" style="${commonStyle}object-fit:cover;display:none;" alt="Avatar"
                onerror="this.onerror=null;this.style.display='none';const fb=this.nextElementSibling;if(fb){fb.style.display='flex';}">
                <div ${dataAttr} style="${fallbackStyle}">${initial}</div>`;
    }

    // 3) TOUT le reste (GLB, RPM, null) → DiceBear > initiales
    return `<img ${dataAttr} src="${diceUrl}" style="${commonStyle}object-fit:cover;display:inline-block;" alt="Avatar"
            onerror="this.onerror=null;this.style.display='none';const fb=this.nextElementSibling;if(fb){fb.style.display='flex';}">
            <div ${dataAttr} style="${fallbackStyle}">${initial}</div>`;
}

function refreshAllAvatarsForUser(userOrId) {
    try {
        if (typeof document === 'undefined') return;
        const uid = safeUserId(typeof userOrId === 'object' ? userOrId : { id: String(userOrId || '') });
        if (!uid) return;
        const targets = document.querySelectorAll(`[data-avatar-for="${uid}"]`);
        if (!targets || targets.length === 0) return;

        const processedParents = new WeakSet();
        const groups = [];
        targets.forEach(el => {
            const parent = el.parentElement;
            if (!parent || processedParents.has(parent)) return;
            processedParents.add(parent);

            const firstEl = parent.querySelector(`[data-avatar-for="${uid}"]`);
            if (!firstEl) return;
            const widthMatch = (firstEl.getAttribute('style') || '').match(/width:\s*([^;]+)/);
            const size = widthMatch ? widthMatch[1].trim() : "40px";
            groups.push({ parent, size });
        });

        if (groups.length === 0) return;

        let user = null;
        try { user = JSON.parse(localStorage.getItem("wbc_user") || "{}") || null; } catch {}
        if (!user || safeUserId(user) !== uid) { user = { _id: uid, id: uid }; }
        const freshHtml = createAvatarHtml(user, "40px");

        groups.forEach(({ parent, size }) => {
            const sizedHtml = createAvatarHtml(user, size);
            while (parent.firstChild) parent.removeChild(parent.firstChild);
            parent.insertAdjacentHTML("beforeend", sizedHtml);
        });
    } catch (e) { console.warn("refreshAllAvatarsForUser failed:", e); }
}

function bindGlobalAvatarAutoRefresh() {
    try {
        if (typeof window === 'undefined' || bindGlobalAvatarAutoRefresh.done) return;
        bindGlobalAvatarAutoRefresh.done = true;

        window.addEventListener("wbc:avatarThumbReady", (e) => {
            const uid = e?.detail?.userId;
            if (uid) setTimeout(() => refreshAllAvatarsForUser(uid), 0);
        });

        const userForPoll = (() => { try { return JSON.parse(localStorage.getItem("wbc_user") || "{}"); } catch { return null; } })();
        const myUid = safeUserId(userForPoll);
        if (!myUid) return;
        let lastSuffix = "";
        setInterval(() => {
            try {
                const raw = localStorage.getItem("wbc_avatar_thumb:" + myUid) || "";
                const suffix = raw.slice(-20);
                if (suffix && suffix !== lastSuffix) {
                    lastSuffix = suffix;
                    refreshAllAvatarsForUser(myUid);
                }
            } catch {}
        }, 2500);
    } catch {}
}

if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
        document.addEventListener("DOMContentLoaded", bindGlobalAvatarAutoRefresh);
    } else {
        bindGlobalAvatarAutoRefresh();
    }
}

